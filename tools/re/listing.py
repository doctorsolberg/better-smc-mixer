"""Navigate a pi32v2 objdump listing of the stock SMC-Mixer app (V012).

Usage: python3 -I tools/re/listing.py LISTING CMD [ARGS]
  dump ADDR [N]   N instructions from ADDR (hex VMA), annotated
  callers ADDR    direct call sites of the function at ADDR
  args ADDR...    call sites of the functions at ADDR... with the constants r0-r3 get before the
                  call (for example the ROM's P33 accessors: which power registers are written)
  sfr             instructions that load a GPIO port register address
  stats           instruction and call-target counts

The listing comes from tools/re/disasm_stock.sh. Call and branch targets are resolved (target =
next instruction + offset, masked to 25 bits); code of .data_code is shown at its RAM address.
ROM function names come from the SDK linker script generated by tools/env/smoke_build.sh
(build/sdk-smoke/cpu/br25/sdk.ld, or the ROM_LD environment variable). Standard library only.
"""
import re
import sys
from collections import defaultdict

LINE = re.compile(r"^\s*([0-9a-f]{7}):\s+((?:[0-9a-f]{2} )+)\s*\t(.*)$")
CONT = re.compile(r"^\s+\t(.*)$")

# .data_code is stored after .data and copied to RAM by crt0
DC_FLASH, DC_RAM, DC_LEN = 0x1E204E4, 0x16C00, 6624

SFR = {}
for name, base in (("PA", 0x1E5000), ("PB", 0x1E5040), ("PC", 0x1E5080), ("PD", 0x1E50C0)):
    for i, reg in enumerate(("OUT", "IN", "DIR", "DIE", "PU", "PD", "HD0", "HD", "DIEH")):
        SFR[base + 4 * i] = "%s.%s" % (name, reg)


NAMES = {}


def load_rom(path):
    for line in open(path):
        m = re.match(r"\s*(\w+) = ABSOLUTE\((0x[0-9a-fA-F]+)\);", line)
        if m:
            NAMES[int(m.group(2), 16)] = m.group(1)


def vma(addr):
    if DC_FLASH <= addr < DC_FLASH + DC_LEN:
        return addr - DC_FLASH + DC_RAM
    return addr


class Ins:
    __slots__ = ("addr", "size", "text", "target", "kind")

    def __init__(self, addr, size, text):
        self.addr, self.size, self.text = addr, size, text.strip()
        self.target, self.kind = None, None
        m = re.match(r"(?:if \(.*\) )?(call|goto) (-?\d+)(?:\s*<[^>]*>)?\s*$", self.text)
        if m:
            self.kind = m.group(1) if not self.text.startswith("if") else "branch"
            self.target = (vma(addr) + size + int(m.group(2))) & 0x1FFFFFF


def load(path):
    ins = []
    for line in open(path):
        m = LINE.match(line)
        if m:
            a = int(m.group(1), 16)
            ins.append(Ins(a, len(m.group(2).split()), m.group(3)))
        else:
            c = CONT.match(line)
            if c and ins and c.group(1).strip() not in ("}",):
                ins[-1].text += " ; " + c.group(1).strip()
    return ins


def index(ins):
    by_vma = {vma(i.addr): n for n, i in enumerate(ins)}
    calls = defaultdict(list)  # target -> [caller addr]
    for i in ins:
        if i.kind == "call":
            calls[i.target].append(vma(i.addr))
    starts = sorted(calls)
    return by_vma, calls, starts


def func_of(addr, starts):
    import bisect
    k = bisect.bisect_right(starts, addr) - 1
    return starts[k] if k >= 0 else None


def annotate(i):
    t = i.text
    for m in re.finditer(r"= (\d{6,})\b", t):
        v = int(m.group(1))
        if v in SFR:
            t += "   ; " + SFR[v]
        elif 0x1E00000 <= v < 0x1F00000:
            t += "   ; 0x%x" % v
        elif 0x10000 <= v < 0x20000:
            t += "   ; ram 0x%x" % v
    if i.target is not None:
        t += "   -> %x %s" % (i.target, NAMES.get(i.target, ""))
    return t


def dump(ins, by_vma, start, count):
    n = by_vma.get(start)
    if n is None:
        print("no instruction at %x" % start)
        return
    for i in ins[n:n + count]:
        print("%7x  %s" % (vma(i.addr), annotate(i)))


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit(__doc__.strip())
    import os
    rom_ld = os.environ.get("ROM_LD", os.path.join(os.path.dirname(__file__), "../../build/sdk-smoke/cpu/br25/sdk.ld"))
    if os.path.exists(rom_ld):
        load_rom(rom_ld)
    ins = load(sys.argv[1])
    by_vma, calls, starts = index(ins)
    cmd = sys.argv[2]
    if cmd == "dump":
        dump(ins, by_vma, int(sys.argv[3], 16), int(sys.argv[4]) if len(sys.argv) > 4 else 60)
    elif cmd == "callers":
        t = int(sys.argv[3], 16)
        for c in calls.get(t, []):
            print("%x in func %x" % (c, func_of(c, starts) or 0))
    elif cmd == "args":
        # Call sites of the functions at the given addresses with r0-r3 as set before the call: the
        # last assignment of each in the same straight run of code (back to the previous call,
        # return or unconditional jump). Branches into that run are not followed, so a value is
        # a lead to check in the dump, not a proof.
        for t in (int(a, 16) for a in sys.argv[3:]):
            for c in calls.get(t, []):
                regs, n = {}, by_vma[c] - 1
                while n >= 0 and by_vma[c] - n <= 16:
                    i = ins[n]
                    if i.kind in ("call", "goto") or i.text.startswith("rts") or "goto r" in i.text:
                        break
                    m = re.match(r"(r[0-3]) = (.+)$", i.text)
                    if m and m.group(1) not in regs:
                        v = m.group(2).split(" <")[0].strip()
                        regs[m.group(1)] = v if re.fullmatch(r"-?\d+", v) else "?"
                    n -= 1
                print("%7x in %7x  %s(%s)" % (c, func_of(c, starts) or 0, NAMES.get(t, "%x" % t),
                                               ", ".join(regs.get("r%d" % k, "-") for k in range(4))))
    elif cmd == "sfr":
        for i in ins:
            a = annotate(i)
            if "; P" in a:
                print("%7x in %7x  %s" % (vma(i.addr), func_of(vma(i.addr), starts) or 0, a))
    elif cmd == "stats":
        print(len(ins), "instructions,", len(starts), "call targets")
