def ctype(size):
    return "uint8_t" if size == 1 else "uint16_t"


def comment(text, width=100, indent=""):
    words, lines, cur = text.split(), [], indent + "/*"
    for w in words:
        if len(cur) + 1 + len(w) > width - 3:
            lines.append(cur)
            cur = indent + " *"
        cur += " " + w
    lines.append(cur + " */")
    return "\n".join(lines)


def enum_c(e, kinds_note=""):
    out = [comment("%s%s" % (e.doc, kinds_note)), "enum %s {" % e.c]
    w = max(len(v["c"]) for v in e.values) + 1
    for v in e.values:
        out.append("    %-*s /* %s: %s */" % (w, v["c"] + ",", v["json"], v["doc"]))
    out.append("};")
    return "\n".join(out)


def fields_c(fields, enum_of):
    """Struct members with their file key and doc; a comment too long for the line goes above."""
    out = []
    decls = [(f, "%s %s;" % (ctype(f.size), f.c)) for f in fields if f.c]
    w = max(len(d) for _, d in decls)
    for f, d in decls:
        note = "%s: %s" % (f.json or "flags", f.doc)
        e = enum_of(f)
        if e:
            note += " (enum %s)" % e
        line = "    %-*s /* %s */" % (w, d, note)
        if len(line) > 100:
            out.append(comment(note, indent="    "))
            out.append("    " + d)
        else:
            out.append(line)
    return out


def gen_core(S):
    out = [HEADER % "Included by core.h, after the panel's counts." + """#ifndef CORE_CONFIG_H
#define CORE_CONFIG_H

#include <stdint.h>

#ifndef CORE_STRIPS
#error "include core.h"
#endif
"""]
    for e in S.enums.values():
        out.append(enum_c(e) + "\n")
    flags = next(f for f in S.assign_fields if f.members)
    out.append("/* %s (struct core_assign.flags) */" % flags.doc)
    for m in flags.members:
        names = m["c"] if isinstance(m["c"], list) else [m["c"]]
        vals = [v for k, v in m["values"].items() if v]
        keys = [k for k, v in m["values"].items() if v]
        for c, v, k in zip(names, vals, keys):
            out.append("#define %s 0x%02xu /* %s %s: %s */" % (c, v, m["json"], k, m.get("valueDoc", {}).get(k, m["doc"])))
    for f in S.assign_fields:
        for n in f.named:
            out.append("#define %s %d /* %s %s: %s */" % (n["c"], n["value"], f.json, n["json"], n["doc"]))
    out.append("")
    a = S.raw["assignment"]

    def assign_enum(f):
        if f.enum == "kindMode":
            return "core_pickup / core_enc_mode / core_press"
        return S.enums[f.enum].c if f.enum else None

    out.append(comment(a["doc"]))
    out.append("struct core_assign {")
    out += fields_c(S.assign_fields, assign_enum)
    out.append("};\n")
    c = S.raw["control"]
    out.append(comment(c["doc"]))
    out.append("""struct core_control {
    struct core_assign normal;
    struct core_assign shift; /* CORE_SHIFT_OVERRIDE */
    uint8_t shift_kind;       /* enum core_shift_kind */
};
""")
    st = S.raw["strip"]
    out.append(comment(st["doc"]))
    out.append("struct core_strip {")
    single = [x["c"] for x in st["controls"] if "[" not in x["c"]]
    arrays = {}
    for x in st["controls"]:
        if "[" in x["c"]:
            arrays.setdefault(x["c"].split("[")[0], []).append(x["json"])
    out.append("    struct core_control %s;" % ", ".join(single))
    for name, members in arrays.items():
        out.append("    struct core_control %s[%d]; /* %s */" % (name, len(members), ", ".join(m.upper() for m in members)))
    out.append("};\n")
    pr = S.raw["preset"]
    out.append(comment(pr["doc"]))
    out.append("struct core_preset {")
    out.append("    struct core_strip page[CORE_PAGES][CORE_STRIPS];")
    out.append("    struct core_control row[CORE_ROW_BUTTONS]; /* %s */" % " ".join(b["json"] for b in S.row))
    out += fields_c(S.preset_fields, lambda f: S.enums[f.enum].c if f.enum else None)
    out.append("};\n")
    gl = S.raw["global"]
    out.append(comment(gl["doc"]))
    out.append("struct core_global {")
    out += fields_c(S.global_fields, lambda f: S.enums[f.enum].c if f.enum else None)
    out.append("};\n")
    out.append("""struct core_config {
    struct core_global global;
    struct core_preset preset[CORE_PRESETS];
};

#endif /* CORE_CONFIG_H */
""")
    return "\n".join(out)


def fit(text):
    """C lines over 100 columns: a trailing comment moves above its line."""
    out = []
    for line in text.split("\n"):
        if len(line) > 100 and line.endswith(" */") and " /* " in line:
            code, note = line[:-3].split(" /* ", 1)
            indent = code[:len(code) - len(code.lstrip())]
            out.append(comment(note, indent=indent))
            out.append(code.rstrip())
        else:
            out.append(line)
    return "\n".join(out)


def mask_of(indexes):
    m = 0
    for i in indexes:
        m |= 1 << i
    return m


def gen_tables(S):
    msg = S.msg
    kinds = list(S.kinds.values())
    types_code = {None: "CFG_T_ANY", "notNone": "CFG_T_NOT_NONE", "withNumber": "CFG_T_NUMBER",
                  "withValue": "CFG_T_VALUE"}
    out = [HEADER % "Included by firmware/config/cfgbin.c only." + """#ifndef CFG_SCHEMA_H
#define CFG_SCHEMA_H

#include <stddef.h>
#include <stdint.h>

#include "core.h"

#define CFG_OFF(s, m) ((uint16_t)offsetof(struct s, m))
_Static_assert(sizeof(struct core_preset) <= 0xFFFF, "the field offsets need more than 16 bits");
"""]
    b = S.binary
    out.append("#define CFG_SCHEMA_VERSION %d" % S.version)
    out.append("#define CFG_BINARY_VERSION %d" % S.binary_version)
    out.append("#define CFG_MAGIC \"%s\"" % b["magic"])
    out.append("#define CFG_HEADER_SIZE %d" % b["headerSize"])
    for r in b["records"]:
        out.append(comment("%s: %s" % (r["name"], r["doc"])))
        out.append("#define CFG_TAG_%s %d" % (r["name"].upper(), r["tag"]))
    out.append("#define CFG_TAG_OPTIONAL 0x%02xu /* unknown records with it are skipped, others refused */" % b["optionalTagBit"])
    out.append("#define CFG_ROW_PAGE %d" % b["rowPage"])
    out.append("#define CFG_ROW_NAV 0x%03xu /* row buttons whose Shift layer is the firmware's */" % mask_of(
        i for i, x in enumerate(S.row) if x.get("nav")))
    out.append("#define CFG_SHIFT_KINDS %d" % len(S.enums["shiftKind"]))
    out.append("")
    out.append("/* message types */")
    out.append("#define CFG_MSG_COUNT %d" % len(msg))
    out.append("#define CFG_TYPES_NOT_NONE 0x%04xu" % mask_of(S.type_set("notNone")))
    out.append("#define CFG_TYPES_NUMBER 0x%04xu" % mask_of(S.type_set("withNumber")))
    out.append("#define CFG_TYPES_VALUE 0x%04xu" % mask_of(S.type_set("withValue")))
    out.append("static const uint16_t cfg_type_max[CFG_MSG_COUNT] = {%s};" % ", ".join(
        str(S.type_max(i)) for i in range(len(msg))))
    out.append("static const uint16_t cfg_number_max[CFG_MSG_COUNT] = {%s};" % ", ".join(
        str(S.number_max(i) or 0) for i in range(len(msg))))
    out.append("")
    out.append("/* control kinds */")
    out.append("enum cfg_kind { %s, CFG_KINDS };" % ", ".join("CFG_KIND_%s" % k.name.upper() for k in kinds))
    out.append("static const uint16_t cfg_kind_types[CFG_KINDS] = {%s};" % ", ".join(
        "0x%04xu" % mask_of(k.types) for k in kinds))
    out.append("static const uint8_t cfg_kind_modes[CFG_KINDS] = {%s};" % ", ".join(str(len(k.mode_enum)) for k in kinds))
    out.append("static const uint8_t cfg_kind_mode_default[CFG_KINDS] = {\n    %s,\n};" % ", ".join(
        k.mode_enum.values[k.mode_default]["c"] for k in kinds))
    fine = [k for k in kinds if k.shift_default == "fine"]
    out.append("#define CFG_KINDS_FINE 0x%02xu /* kinds whose default Shift layer is fine mode */" % mask_of(
        kinds.index(k) for k in fine))
    out.append("#define CFG_FINE_MODE %s" % S.kinds["encoder"].mode_enum.values[
        S.kinds["encoder"].mode_enum.index(S.fine["mode"])]["c"])
    out.append("/* strip controls: id / 8 is the group, id % 8 the strip */")
    out.append("static const struct {\n    uint8_t kind;\n    uint16_t off;\n} cfg_strip_control[%d] = {" % len(S.strip_controls))
    for x in S.strip_controls:
        out.append("    {CFG_KIND_%s, CFG_OFF(core_strip, %s)}, /* %s */" % (x["kind"].upper(), x["c"], x["json"]))
    out.append("};")
    out.append("")
    out.append("""/* A field of the assignment, a preset or the global settings, in binary order. */
enum cfg_types { CFG_T_ANY, CFG_T_NOT_NONE, CFG_T_NUMBER, CFG_T_VALUE };
enum cfg_from {
    CFG_CONST,      /* min, max, def */
    CFG_MIDDLE,     /* the default: the middle of the layer's lo and hi, rounded up */
    CFG_KIND_MODE,  /* the default: the kind's mode */
    CFG_TYPE_MAX,   /* the type's largest value */
    CFG_NUMBER_MAX, /* the type's largest number */
    CFG_KIND_MODES, /* the largest: the kind's last mode */
};
struct cfg_field {
    uint16_t off;  /* offsetof in its struct */
    uint8_t size;  /* 1 or 2 */
    uint8_t types; /* enum cfg_types: the types it applies to */
    uint8_t kinds; /* the kinds it applies to, a bit per enum cfg_kind */
    uint8_t modes; /* the modes it applies to, a bit per mode of the kind */
    uint8_t max_from, def_from; /* enum cfg_from */
    uint16_t min, max, def;     /* the device's values */
};
""")

    def field_row(f, struct_name, kind_all=True):
        off = "CFG_OFF(%s, %s)" % (struct_name, f.c)
        ap = f.applies
        types = types_code[ap.get("types")]
        kmask = mask_of(kinds.index(S.kinds[k]) for k in ap["kinds"]) if "kinds" in ap else (1 << len(kinds)) - 1
        if "modes" in ap:
            kind = S.kinds[ap["kinds"][0]]
            modes = mask_of(kind.mode_enum.index(m) for m in ap["modes"])
        else:
            modes = 0xFF
        lo = f.min - f.offset
        if f.enum and f.enum != "kindMode":
            e = S.enums[f.enum]
            excluded = [e.index(x) for x in f.exclude]
            if excluded != list(range(len(excluded))):
                raise schema_mod.SchemaError("%s: only a prefix of an enum can be excluded" % f.json)
            lo, max_from, hi = len(excluded), "CFG_CONST", len(e) - 1
        elif f.enum == "kindMode":
            max_from, hi = "CFG_KIND_MODES", 0
        elif f.members:
            max_from, hi = "CFG_CONST", sum(m["mask"] for m in f.members)
        elif f.max == "typeMax":
            max_from, hi = "CFG_TYPE_MAX", 0
        elif f.max == "numberMax":
            max_from, hi = "CFG_NUMBER_MAX", 0
        else:
            max_from, hi = "CFG_CONST", max([f.max - f.offset] + [n["value"] for n in f.named])
        d = f.default
        if d == "middle":
            def_from, dv = "CFG_MIDDLE", 0
        elif d == "kindMode":
            def_from, dv = "CFG_KIND_MODE", 0
        elif d == "typeMax":
            def_from, dv = "CFG_TYPE_MAX", 0
        else:
            def_from, dv = "CFG_CONST", S.default(f)
        return "    /* %s */\n    {%s, %d, %s, 0x%02x, 0x%02x, %s, %s, %d, %d, %d}," % (f.json or "flags",
            off, f.size, types, kmask, modes, max_from, def_from, lo, hi, dv)

    for name, fields, struct_name in (("assign", S.assign_fields, "core_assign"),
                                       ("preset", S.preset_fields, "core_preset"),
                                       ("global", S.global_fields, "core_global")):
        out.append("#define CFG_%s_FIELDS %d" % (name.upper(), len(fields)))
        out.append("static const struct cfg_field cfg_%s_field[CFG_%s_FIELDS] = {" % (name, name.upper()))
        out += [field_row(f, struct_name) for f in fields]
        out.append("};")
    flags = next(f for f in S.assign_fields if f.members)
    out.append("")
    out.append("/* the flags' members: a mask, its shift, and the values allowed, a bit per (value >> shift) */")
    out.append("#define CFG_FLAG_MEMBERS %d" % len(flags.members))
    out.append("static const struct {\n    uint8_t mask, shift, allowed;\n} cfg_flag_member[CFG_FLAG_MEMBERS] = {")
    for m in flags.members:
        shift = (m["mask"] & -m["mask"]).bit_length() - 1
        out.append("    {0x%02xu, %d, 0x%02xu}, /* %s */" % (m["mask"], shift, mask_of(v >> shift for v in m["values"].values()), m["json"]))
    out.append("};")
    out.append("\n#endif /* CFG_SCHEMA_H */\n")
    return "\n".join(out)


