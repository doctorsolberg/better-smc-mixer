def gen_json_schema(S):
    msg = S.msg
    defs = {}

    def enum_values(e, exclude=()):
        return [v for v in e.json if v not in exclude]

    def doc_enum(e):
        return "; ".join("%s: %s" % (v["json"], v["doc"]) for v in e.values)

    name = {"type": "string", "maxLength": S.name_max}
    value_keys = [f.json for f in S.assign_fields if f.max == "typeMax"]

    for kind in S.kinds.values():
        props = {}
        for f in S.assign_fields:
            if f.c == "msg":
                props["type"] = {"enum": [msg.json[t] for t in kind.types],
                                 "description": "%s. %s" % (f.doc, doc_enum(msg))}
                continue
            ap = f.applies
            if "kinds" in ap and kind.name not in ap["kinds"]:
                continue
            if f.members:
                for m in f.members:
                    vals = [json.loads(k) if k in ("true", "false") else k for k in m["values"]]
                    props[m["json"]] = {"enum": vals, "description": m["doc"]}
                continue
            if f.enum == "kindMode":
                props[f.json] = {"enum": kind.mode_enum.json, "description": "%s. %s" % (
                    kind.mode_enum.doc, doc_enum(kind.mode_enum))}
                continue
            mx = f.max
            if mx == "numberMax":
                mx = max(msg.values[t].get("numberMax", 0) for t in kind.types)
            elif mx == "typeMax":
                mx = max(S.type_max(t) for t in kind.types)
            number = {"type": "integer", "minimum": f.min, "maximum": mx}
            if f.named:
                props[f.json] = {"anyOf": [number] + [{"const": n["json"], "description": n["doc"]} for n in f.named],
                                 "default": f.default, "description": f.doc}
            else:
                props[f.json] = dict(number, description=f.doc)
            if f.required:
                props[f.json]["description"] += " (required where it applies)"
        rules = []
        # the 14-bit and the number limits by type
        number_top = max(msg.values[t].get("numberMax", 0) for t in kind.types)
        for t in kind.types:
            v = msg.values[t]
            then = {}
            if "numberMax" in v and v["numberMax"] < number_top:
                then["number"] = {"maximum": v["numberMax"]}
            if "max" in v and v["max"] < 16383:
                for k in value_keys:
                    if k in props:
                        then[k] = {"maximum": v["max"]}
            if then:
                rules.append({"if": {"properties": {"type": {"const": v["json"]}}, "required": ["type"]},
                              "then": {"properties": then}})
        absent = [k for k in ("number",) if k in props]
        no_number = [msg.json[t] for t in kind.types if "numberMax" not in msg.values[t] and t != msg.index("none")]
        if absent and no_number:
            rules.append({"if": {"properties": {"type": {"enum": no_number}}, "required": ["type"]},
                          "then": {"not": {"required": ["number"]}}})
        # n: only in div and step, and there required (an absent mode is the kind's default, which
        # is neither)
        for f in S.assign_fields:
            if f.json in props and "modes" in f.applies:
                modes = f.applies["modes"]
                if kind.mode_enum.json[kind.mode_default] in modes:
                    raise schema_mod.SchemaError("%s: the default mode takes %s" % (kind.name, f.json))
                rules.append({"if": {"properties": {"mode": {"enum": modes}}, "required": ["mode"]},
                              "then": {"required": [f.json]} if f.required else True,
                              "else": {"not": {"required": [f.json]}}})
        others = [k for k in props if k != "type"]
        # A Shift layer of its own is written in full, as the Normal layer: its type at least, and
        # not none ("block" says that).
        layer_props = dict(props)
        layer_props["type"] = dict(props["type"], enum=[t for t in props["type"]["enum"] if t != "none"])
        layer_props["name"] = name  # its own name, when it does something else than the Normal layer
        defs[kind.name + "Layer"] = {
            "type": "object", "properties": layer_props, "additionalProperties": False, "required": ["type"],
            "description": "a Shift layer of its own, written in full as the Normal layer is", "allOf": rules}
        rules = rules + [{"if": {"properties": {"type": {"const": "none"}}, "required": ["type"]},
                          "then": {"properties": {k: False for k in others}}}]
        ctl_props = dict(props)
        ctl_props["name"] = name
        ctl = {"type": "object", "properties": ctl_props, "additionalProperties": False,
               "dependentRequired": {k: ["type"] for k in others},
               "description": "%s: the Normal layer's fields, and its Shift layer. %s" % (
                   kind.name, S.raw["control"]["shift"]["doc"])}
        ctl["allOf"] = rules
        ctl_props["shift"] = {"oneOf": [{"enum": ["inherit", "block"]}, {"$ref": "#/$defs/%sLayer" % kind.name}]}
        defs[kind.name] = ctl
        if kind.name == "button":
            nav = json.loads(json.dumps(ctl))
            del nav["properties"]["shift"]
            nav["description"] = "a navigation button: the Shift layer is the firmware's (FR-SH-02)"
            defs["navButton"] = nav

    def setting(f):
        if f.enum:
            e = S.enums[f.enum]
            return {"enum": enum_values(e, f.exclude), "default": f.default,
                    "description": "%s. %s" % (f.doc, doc_enum(e))}
        return {"type": "integer", "minimum": f.min, "maximum": f.max, "default": f.default, "description": f.doc}

    defs["strip"] = {"type": "object", "additionalProperties": False,
                     "properties": {c["json"]: {"$ref": "#/$defs/%s" % c["kind"]} for c in S.strip_controls}}
    defs["page"] = {"type": "object", "additionalProperties": False, "properties": {
        "name": name, "strips": {"type": "array", "maxItems": S.device["strips"],
                                 "items": {"anyOf": [{"$ref": "#/$defs/strip"}, {"type": "null"}]}}}}
    row = {b["json"]: {"$ref": "#/$defs/%s" % ("navButton" if b.get("nav") else "button")} for b in S.row}
    preset_props = {"name": name}
    for f in S.preset_fields:
        preset_props[f.json] = setting(f)
    preset_props["row"] = {"type": "object", "additionalProperties": False, "properties": row,
                           "description": S.raw["row"]["doc"]}
    preset_props["pages"] = {"type": "array", "items": {"anyOf": [{"$ref": "#/$defs/page"}, {"type": "null"}]}}
    defs["preset"] = {"type": "object", "additionalProperties": False, "properties": preset_props,
                      "description": S.raw["preset"]["doc"]}
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "SMC-Mixer configuration",
        "description": "GENERATED by tools/smcconf/gen.py from config/schema.json. %s tools/smcconf checks "
                       "more than this schema can say (the Shift layer over the Normal layer's fields)." % S.raw["file"]["doc"],
        "type": "object",
        "required": ["schemaVersion"],
        "additionalProperties": False,
        "properties": {
            "schemaVersion": {"const": S.version},
            "id": {"type": "string", "pattern": "^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$",
                   "description": "the configuration's UUID (FR-APP-24)"},
            "revision": {"type": "integer", "minimum": 0, "maximum": 4294967295},
            "name": name,
            "global": {"type": "object", "additionalProperties": False,
                       "properties": {f.json: setting(f) for f in S.global_fields},
                       "description": S.raw["global"]["doc"]},
            "presets": {"type": "array", "items": {"anyOf": [{"$ref": "#/$defs/preset"}, {"type": "null"}]}},
        },
        "$defs": defs,
    }


def FIELDS_BY_JSON(S):
    return {f.json: f for f in S.assign_fields if f.json}


