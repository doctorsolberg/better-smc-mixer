def gen_doc(S):
    msg = S.msg
    out = ["", "Message types (`type`):", "", "| Type | Value range | Number | Fader | Encoder | Button | What |",
           "|---|---|---|---|---|---|---|"]
    for i, v in enumerate(msg.values):
        out.append("| `%s` | %s | %s | %s | %s | %s | %s |" % (
            v["json"], "0–%d" % v["max"] if "max" in v else "—", "0–%d" % v["numberMax"] if "numberMax" in v else "—",
            *("✓" if i in S.kinds[k].types else "—" for k in ("fader", "encoder", "button")), v["doc"]))
    out += ["", "A layer's fields:", "", "| Key | Values | Default | Applies to | What |", "|---|---|---|---|---|"]
    for f in S.assign_fields:
        ap = f.applies
        where = []
        if "kinds" in ap:
            where.append(", ".join(ap["kinds"]))
        if "types" in ap:
            where.append({"notNone": "any type but none", "withNumber": "types with a number",
                          "withValue": "types with a value range"}[ap["types"]])
        if "modes" in ap:
            where.append("modes " + ", ".join(ap["modes"]))
        where = "; ".join(where) or "all"
        if f.members:
            for m in f.members:
                out.append("| `%s` | %s | `%s` | %s | %s |" % (
                    m["json"], ", ".join("`%s`" % k for k in m["values"]), json.dumps(m["default"]).strip('"'),
                    where, m["doc"]))
            continue
        if f.enum == "kindMode":
            vals = "; ".join("%s: %s" % (k.name, ", ".join("`%s`" % x for x in k.mode_enum.json)) for k in S.kinds.values())
            dflt = "; ".join("%s `%s`" % (k.name, k.mode_enum.json[k.mode_default]) for k in S.kinds.values())
        elif f.enum:
            vals, dflt = "see above", "`%s`" % f.default
        else:
            mx = {"numberMax": "the type's", "typeMax": "the type's"}.get(f.max, f.max)
            vals = ", ".join(["%s–%s" % (f.min, mx)] + ["`%s`" % n["json"] for n in f.named])
            dflt = "— (required)" if f.required else {
                "typeMax": "the type's largest", "middle": "the middle of `lo` and `hi`"}.get(f.default, "`%s`" % f.default)
        out.append("| `%s` | %s | %s | %s | %s |" % (f.json, vals, dflt, where, f.doc))
    for title, fields in (("A preset's settings", S.preset_fields), ("Global settings (`global`)", S.global_fields)):
        out += ["", title + ":", "", "| Key | Values | Default | What |", "|---|---|---|---|"]
        for f in fields:
            if f.enum:
                e = S.enums[f.enum]
                vals = ", ".join("`%s`" % v for v in e.json if v not in f.exclude)
            else:
                vals = "%d–%d" % (f.min, f.max)
            out.append("| `%s` | %s | `%s` | %s |" % (f.json, vals, f.default, f.doc))
    out += ["", "Kinds: the default mode and Shift layer:", "", "| Kind | Mode default | Shift default |", "|---|---|---|"]
    for k in S.kinds.values():
        out.append("| %s | `%s` | %s |" % (k.name, k.mode_enum.json[k.mode_default],
                                           "fine: the Normal layer in mode `fine`" if k.shift_default == "fine"
                                           else "`inherit`"))
    out.append("")
    return "\n".join(out)


def outputs(S):
    with open(DOC) as f:
        doc = f.read()
    if BEGIN not in doc or END not in doc:
        raise schema_mod.SchemaError("docs/config.md has no generated markers")
    head, rest = doc.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return {
        OUT_CORE: fit(gen_core(S)),
        OUT_TABLES: fit(gen_tables(S)),
        OUT_JSON_SCHEMA: json.dumps(gen_json_schema(S), indent=2, ensure_ascii=False) + "\n",
        DOC: head + BEGIN + "\n" + gen_doc(S) + END + tail,
    }


def main(argv):
    check = "--check" in argv
    S = schema_mod.load()
    stale = []
    for path, text in outputs(S).items():
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w") as f:
                    f.write(text)
    if check:
        if stale:
            print("gen: not what config/schema.json gives: %s (run python3 -I tools/smcconf/gen.py)" % ", ".join(stale))
            return 1
        print("gen: the generated files are up to date")
        return 0
    print("gen: wrote %s" % (", ".join(stale) if stale else "nothing (all up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
